export function scoreCareerQuiz(choices) {
  let sales = 0
  let recruit = 0
  choices.forEach((choice, index) => {
    const option = CAREER_QUIZ[index]?.a[choice]
    if (!option) return
    sales += option.s
    recruit += option.r
  })
  if (Math.abs(sales - recruit) <= 1) return "both"
  return sales > recruit ? "sales" : "recruit"
}

